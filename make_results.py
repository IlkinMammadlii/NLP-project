# ------------------------------------------------------------------ helpers
def guard(name):
    def deco(fn):
        def wrapped(*a, **k):
            try:
                return fn(*a, **k)
            except Exception as e:  # noqa: BLE001
                PROBLEMS.append(f"{name}: {e!r}")
                traceback.print_exc()
                return None
        return wrapped
    return deco


def fmt(x, d=2, sign=False):
    if x is None or not np.isfinite(x):
        return NA
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def macro(name: str, value: str) -> None:
    MACROS[name] = value


def tex_write(name: str, body: str) -> None:
    TAB.mkdir(exist_ok=True)
    if "\\begin{tabular}" in body and "\\resizebox" not in body:  # never wider than the column/page
        body = body.replace("\\begin{tabular}", "\\begin{adjustbox}{max width=\\linewidth}\n\\begin{tabular}", 1)
        body = body.replace("\\end{tabular}", "\\end{tabular}\n\\end{adjustbox}", 1)
    (TAB / f"{name}.tex").write_text("% generated by make_results.py -- do not edit\n" + body, encoding="utf-8")


def na_table(name: str, caption: str, label: str) -> None:
    tex_write(name, "\\begin{table}[t]\\centering\\small\n\\textit{" + NA + ": results not available yet.}\n"
              f"\\caption{{{caption}}}\\label{{{label}}}\n\\end{{table}}\n")


def evals(split: str = "test") -> dict:
    """{run_id: newest eval row} for the full eval set, current config, sampling seed 0."""
    out = {}
    for r in read_jsonl(path("runs", "evals.jsonl")):
        if r["split"] != split or r.get("seed", 0) != 0 or r.get("config_version") != CONFIG_VERSION:
            continue
        if split == "test" and r.get("n_prompts") != 500:
            continue  # the full Dolly test set only
        out[r["run_id"]] = r  # newest wins
    return out


def seeds_of(ev: dict, key: str, seeds=(1, 2, 3)) -> dict:
    return {s: ev[f"{key}_s{s}_{CONFIG_VERSION}"] for s in seeds if f"{key}_s{s}_{CONFIG_VERSION}" in ev}


def mstd(vals: list):
    v = np.array([x for x in vals if x is not None and np.isfinite(x)], dtype=float)
    if not len(v):
        return None, None, 0
    return float(v.mean()), (float(v.std(ddof=1)) if len(v) > 1 else None), len(v)


def cell(vals, d):
    m, s, n = mstd(vals)
    if m is None:
        return NA
    return f"{m:.{d}f}" + (f"$\\pm${s:.{d}f}" if s is not None else "")


def head(cols):
    return " & ".join("\\makecell{" + h + "}" for _, h, _, _ in cols)


