def recovery(ev, arm_key, metric, s):
    a, t, f = (seeds_of(ev, k).get(s) for k in (arm_key, TOP8, FULL))
    if not (a and t and f) or any(x.get(metric) is None for x in (a, t, f)):
        return None
    gap = f[metric] - t[metric]
    return None if abs(gap) < 1e-12 else 100 * (a[metric] - t[metric]) / gap


