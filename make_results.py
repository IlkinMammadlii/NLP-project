@guard("exploratory quality adjustment")
def quality_adjustment():
    """POST-HOC, exploratory (not pre-registered): the matched diversity difference adjusted for the residual
    reference-overlap difference, using full KD's own diversity-per-ROUGE-L slope on test (chord between its
    T = 0.85 and T = 1.0 points, per seed): adj = d_div - slope * d_rouge, averaged over seeds."""
    from cachekd.config import CFG as _C
    from run_final import full, top8
    pts = {}
    for r in read_jsonl(path("runs", "tempsweep.jsonl")):
        if r["split"] == "test" and r.get("n_prompts") == _C["eval_prompts"]:
            pts[(r["run_id"], round(float(r["temperature"]), 6))] = (r["rougeL_sampled"], r["semantic_div"])
    sel = json.loads(path("runs", "final_selection.json").read_text(encoding="utf-8"))
    out = {}
    for name, (tx, ty) in {"A": (sel["T_top8"], 1.0), "B": (1.0, sel["T_full"])}.items():
        adj, slopes = [], []
        for s in (1, 2):
            f1, f85 = pts.get((full(s), 1.0)), pts.get((full(s), 0.85))
            x, y = pts.get((top8(s), round(tx, 6))), pts.get((full(s), round(ty, 6)))
            if not all((f1, f85, x, y)):
                continue
            slope = (f85[1] - f1[1]) / (f85[0] - f1[0])
            slopes.append(slope)
            adj.append((x[1] - y[1]) - slope * (x[0] - y[0]))
        macro(f"Adj{name}", fmt(float(np.mean(adj)), 3, sign=True) if adj else NA)
        out[name] = adj
    macro("AdjSlope", fmt(float(np.mean(slopes)), 3) if slopes else NA)
    return out


